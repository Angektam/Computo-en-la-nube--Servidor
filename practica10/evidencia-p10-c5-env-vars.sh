#!/bin/bash
# ─────────────────────────────────────────────────────────────────────
#  evidencia-p10-c5-env-vars.sh
#  Criterio 6 — Configuración parametrizada (no incrustada)
#  Lista todas las variables de entorno que la imagen requiere
# ─────────────────────────────────────────────────────────────────────

set -euo pipefail
REPO_NAME="inventario-nube-losrojos"
IMAGE_TAG="1.0.0"

echo "═══════════════════════════════════════════════════════"
echo "  EVIDENCIA P10-C5: Variables de entorno de la imagen"
echo "  Criterio: configuración parametrizada, no incrustada"
echo "═══════════════════════════════════════════════════════"

echo ""
echo "┌─────────────────────────────────────────────────────────────────────┐"
echo "│  VARIABLES DE ENTORNO REQUERIDAS — inventario-nube-losrojos:1.0.0  │"
echo "└─────────────────────────────────────────────────────────────────────┘"
echo ""
echo "  ── Servidor ──────────────────────────────────────────────────────"
echo "  PORT              Puerto donde escucha la app (default: 3000)"
echo "  NODE_ENV          Ambiente de ejecución: production | development"
echo ""
echo "  ── CORS ──────────────────────────────────────────────────────────"
echo "  CORS_ORIGIN       Dominio(s) permitidos. Ej: https://mi-app.com"
echo "                    Vacío = acepta todo (solo desarrollo)"
echo ""
echo "  ── Amazon RDS (PostgreSQL) ───────────────────────────────────────"
echo "  DB_HOST           Endpoint del servidor RDS"
echo "  DB_PORT           Puerto PostgreSQL (default: 5432)"
echo "  DB_NAME           Nombre de la base de datos"
echo "  DB_USER           Usuario de la base de datos"
echo "  DB_PASSWORD       Contraseña (¡SECRETO — usar Secrets Manager!)"
echo "  DB_SSL            Activar SSL: true | false"
echo "  DB_SSL_REJECT_UNAUTHORIZED  false solo si el cert es self-signed"
echo ""
echo "  ── AWS Credenciales (solo dev local; en EC2/ECS usar IAM Role) ───"
echo "  AWS_REGION        Región AWS. Ej: us-east-1"
echo "  AWS_ACCESS_KEY_ID      (opcional en producción con IAM Role)"
echo "  AWS_SECRET_ACCESS_KEY  (opcional en producción con IAM Role)"
echo ""
echo "  ── Amazon S3 ─────────────────────────────────────────────────────"
echo "  S3_BUCKET         Nombre del bucket para imágenes de productos"
echo ""
echo "  ── JWT (autenticación) ───────────────────────────────────────────"
echo "  JWT_SECRET        Clave secreta para firmar tokens (¡SECRETO!)"
echo "  JWT_EXPIRES_IN    Duración del token. Ej: 8h"
echo ""
echo "┌─────────────────────────────────────────────────────────────────────┐"
echo "│  EJEMPLO DE USO                                                     │"
echo "└─────────────────────────────────────────────────────────────────────┘"
echo ""
echo "  # Opción A — archivo .env (desarrollo local)"
echo "  docker run -p 3000:3000 --env-file .env ${REPO_NAME}:${IMAGE_TAG}"
echo ""
echo "  # Opción B — variables explícitas (CI/CD o ECS task definition)"
echo "  docker run -p 3000:3000 \\"
echo "    -e NODE_ENV=production \\"
echo "    -e PORT=3000 \\"
echo "    -e DB_HOST=mi-instancia.rds.amazonaws.com \\"
echo "    -e DB_NAME=inventario \\"
echo "    -e DB_USER=postgres \\"
echo "    -e DB_PASSWORD='\$DB_PASSWORD' \\"
echo "    -e JWT_SECRET='\$JWT_SECRET' \\"
echo "    ${REPO_NAME}:${IMAGE_TAG}"
echo ""
echo "┌─────────────────────────────────────────────────────────────────────┐"
echo "│  PROPUESTA DE REDUCCIÓN DE TAMAÑO (Paso 9 de la práctica)          │"
echo "└─────────────────────────────────────────────────────────────────────┘"
echo ""
echo "  1. MULTI-STAGE BUILD"
echo "     Usar una etapa 'builder' con node:20-alpine para instalar"
echo "     dependencias y compilar; copiar solo /app/node_modules y"
echo "     el código a una segunda etapa 'runner' limpia."
echo "     → Ahorra el tamaño de npm, git y herramientas de compilación."
echo ""
echo "  2. DISTROLESS (gcr.io/distroless/nodejs20-debian12)"
echo "     Imagen sin shell, sin apt, sin usuarios — solo Node.js."
echo "     → Reduce ~30-40 MB adicionales y elimina superficie de ataque."
echo ""
echo "  3. npm ci --omit=dev (ya implementado)"
echo "     Ya excluye nodemon y docx (devDependencies) de la imagen final."
echo ""

# ── Verificar variables incrustadas vs. en runtime ────────────────
echo "[ Verificando que NO hay credenciales en el Dockerfile ]"
echo "───────────────────────────────────────────────────────"
cd "$(dirname "$0")/.."
if grep -qiE "(PASSWORD|SECRET|KEY|TOKEN)\s*=" Dockerfile 2>/dev/null; then
  echo "  ❌ ADVERTENCIA: se encontraron posibles credenciales en el Dockerfile"
  grep -iE "(PASSWORD|SECRET|KEY|TOKEN)\s*=" Dockerfile
else
  echo "  ✅ El Dockerfile NO contiene credenciales incrustadas"
fi

echo ""
echo "✅ Criterio 6 verificado: configuración 100% por variables de entorno"
